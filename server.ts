import express from "express";
import path from "path";
import { createServer as createViteServer } from "vite";
import { GoogleGenAI } from "@google/genai";
import dotenv from "dotenv";

dotenv.config();

const app = express();
const PORT = 3000;

app.use(express.json());

// Initialize Gemini API client safely with custom User-Agent for telemetry
let ai: GoogleGenAI | null = null;
function getGeminiClient(): GoogleGenAI {
  if (!ai) {
    const apiKey = process.env.GEMINI_API_KEY;
    if (!apiKey) {
      throw new Error("GEMINI_API_KEY environment variable is not configured.");
    }
    ai = new GoogleGenAI({
      apiKey,
      httpOptions: {
        headers: {
          "User-Agent": "aistudio-build",
        }
      }
    });
  }
  return ai;
}

// AI Spending Analysis & Chat Endpoint
app.post("/api/ai-insight", async (req, res) => {
  try {
    const { query, history, expenses, budget, currency, recentInsightsOnly } = req.body;

    const client = getGeminiClient();

    // Prepare content for Gemini
    const expensesSummary = expenses && expenses.length > 0 
      ? expenses.map((e: any) => `- Date: ${e.date}, Category: ${e.category}, Amount: ${currency || "₹"}${e.amount}, Description: ${e.description || "N/A"}, Mode: ${e.paymentMode || "N/A"}`).join("\n")
      : "No expenses logged yet.";

    const systemPrompt = `You are an expert AI Personal Finance Advisor & Spending Analyst for TMK Expense Tracker.
Your goals are:
1. Provide deep, accurate financial insights based on the user's budget and logged expenses.
2. Be extremely encouraging, helpful, professional, and clear.
3. Use the currency specified by the user (${currency || "₹"}).
4. Answer the user's questions or provide a structured weekly/monthly financial overview.
5. Predict future spending patterns if requested.
6. Provide concrete, actionable tips on where they can save money.

User Profile context:
- Monthly Budget: ${currency || "₹"}${budget || "Not set"}
- Logged Expenses:
${expensesSummary}

Guidelines for formatting:
- Use Markdown for rich formatting (bolding, headers, bullet points).
- Format money values clearly with ${currency || "₹"}.
- Be concise but thorough. Keep responses engaging and structured.`;

    let prompt = "";
    if (recentInsightsOnly) {
      prompt = "Generate a short, elegant 3-bullet financial summary or alert based on my spending and budget. Keep it under 100 words. Be direct, proactive, and friendly.";
    } else {
      prompt = query || "Give me a complete spending analysis, suggest where I can save money, and predict next month's spending based on my historical data.";
    }

    // Build the contents array for multi-turn chat using history if available
    const contents: any[] = [];
    
    if (history && Array.isArray(history)) {
      history.forEach((msg: any) => {
        // Skip the static introductory model message to keep the context clean
        if (msg.text && (msg.text.includes("TMK AI Financial Assistant") || msg.id === "welcome")) return;
        contents.push({
          role: msg.sender === "user" ? "user" : "model",
          parts: [{ text: msg.text }]
        });
      });
    }

    // Append the current query as the latest user message
    contents.push({
      role: "user",
      parts: [{ text: prompt }]
    });

    const response = await client.models.generateContent({
      model: "gemini-3.5-flash",
      contents,
      config: {
        systemInstruction: systemPrompt,
        temperature: 0.7,
        maxOutputTokens: 1000,
      }
    });

    const answer = response.text || "No response generated by AI.";
    res.json({ success: true, answer });
  } catch (error: any) {
    console.error("Gemini API Error:", error);
    res.status(500).json({ 
      success: false, 
      error: error.message || "An error occurred while generating AI insights." 
    });
  }
});

// Vite Dev vs Production Handling
async function setupVite() {
  if (process.env.NODE_ENV !== "production") {
    console.log("Running in DEVELOPMENT mode with Vite dev middleware...");
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: "spa",
    });
    app.use(vite.middlewares);
  } else {
    console.log("Running in PRODUCTION mode. Serving static assets from dist/...");
    const distPath = path.join(process.cwd(), "dist");
    app.use(express.static(distPath));
    app.get("*", (req, res) => {
      res.sendFile(path.join(distPath, "index.html"));
    });
  }

  app.listen(PORT, "0.0.0.0", () => {
    console.log(`Server is running on http://0.0.0.0:${PORT}`);
  });
}

setupVite();
